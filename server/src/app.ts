import cookieParser from "cookie-parser";
import cors from "cors";
import express from "express";
import helmet from "helmet";
import { env } from "./config/env.js";
import { errorHandler } from "./middleware/error-handler.js";
import { activitiesRouter } from "./modules/activities/activities.routes.js";
import { activityExtrasRouter } from "./modules/reviews/reviews.routes.js";
import { activityFeedRouter, upcomingRouter } from "./modules/activity-feed/activity-feed.routes.js";
import { usersRouter } from "./modules/users/users.routes.js";
import { chatRouter, reportsRouter } from "./modules/chat/chat.routes.js";
import { notFound } from "./middleware/not-found.js";
import { adminRouter } from "./modules/admin/admin.routes.js";
import { adminStudentVerificationsRouter } from "./modules/admin/student-verifications.routes.js";
import { authRouter } from "./modules/auth/auth.routes.js";
import { filesRouter } from "./modules/files/files.routes.js";
import { geoRouter } from "./modules/geo/geo.routes.js";
import { healthRouter } from "./modules/health/health.routes.js";
import { registerNotificationListeners } from "./modules/notifications/listeners.js";
import { notificationsRouter, pushRouter, pushSubscriptionsRouter } from "./modules/notifications/notifications.routes.js";
import { subAreasRouter } from "./modules/subareas/subareas.routes.js";
import { adminUniversitiesRouter } from "./modules/universities/universities.admin.routes.js";
import { universitiesRouter } from "./modules/universities/universities.routes.js";
import { adminRiderApplicationsRouter, adminRidersRouter } from "./modules/riders/riders.admin.routes.js";
import { riderRouter } from "./modules/riders/riders.routes.js";
import { carpoolRouter } from "./modules/carpool/carpool.routes.js";
import { foodRouter } from "./modules/food/food.routes.js";
import { rideRouter } from "./modules/ride/ride.routes.js";
import { serviceRouter } from "./modules/service/service.routes.js";
import { disputesRouter } from "./modules/disputes/disputes.routes.js";
import { supportRouter } from "./modules/support/support.routes.js";
import { meRouter } from "./modules/users/me.routes.js";
import { verificationRouter } from "./modules/verification/verification.routes.js";
import { allRequestsRouter } from "./modules/all-requests/all-requests.routes.js";
import { adminContentRouter, contentRouter } from "./modules/content/content.routes.js";

export const app = express();

// B2c: notifications follow activity and chat changes.
registerNotificationListeners();

app.use(helmet());
// Allow both 5173 and 5174 in dev (Vite picks 5174 when 5173 is busy)
const allowedOrigins = [env.CLIENT_URL, env.CLIENT_URL.replace("5173", "5174"), env.CLIENT_URL.replace("5174", "5173")];
app.use(cors({ origin: (origin, cb) => cb(null, !origin || allowedOrigins.includes(origin)), credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.use(cookieParser());

app.use("/api/health", healthRouter);
app.use("/api/auth", authRouter);
app.use("/api/universities", universitiesRouter);
app.use("/api/me/push-subscriptions", pushSubscriptionsRouter);
app.use("/api/me", meRouter);
app.use("/api/sub-areas", subAreasRouter);
app.use("/api/rider", riderRouter);
app.use("/api/activities", activitiesRouter);
app.use("/api/activities", activityExtrasRouter);
app.use("/api/rides", rideRouter);
app.use("/api/food", foodRouter);
app.use("/api/carpool", carpoolRouter);
app.use("/api/service", serviceRouter);
app.use("/api/services/requests", allRequestsRouter);
app.use("/api/all-requests", allRequestsRouter);
app.use("/api/activity", activityFeedRouter);
app.use("/api/upcoming", upcomingRouter);
app.use("/api/users", usersRouter);
app.use("/api/geo", geoRouter);
app.use("/api/chats", chatRouter);
app.use("/api/reports", reportsRouter);
app.use("/api/disputes", disputesRouter);
app.use("/api/support", supportRouter);
app.use("/api/notifications", notificationsRouter);
app.use("/api/push", pushRouter);
app.use("/api/verification", verificationRouter);
app.use("/api/files", filesRouter);
app.use("/api/admin/student-verifications", adminStudentVerificationsRouter);
app.use("/api/admin/universities", adminUniversitiesRouter);
app.use("/api/admin/rider-applications", adminRiderApplicationsRouter);
app.use("/api/admin/riders", adminRidersRouter);
app.use("/api/content", contentRouter);
app.use("/api/admin/content", adminContentRouter);
app.use("/api/admin", adminRouter);

app.use(notFound);
app.use(errorHandler);
